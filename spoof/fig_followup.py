"""Figures for the follow-up analyses (Claims 4, 9, 10, 11, 12 of the spoof write-up). pgfplots, docs/FIGURE_STYLE.md
encoding. Reads ~/spoof-results/local_analyses/local_analyses.json (written by local_analyses.py).
Writes into <out>: random_null, leak_vs_transfer, offpolicy_pairs, item_nesting, coherence_null (+ _legend.tex each).
Usage: python fig_followup.py <out_dir>
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

import numpy as np

J = json.load(open(os.path.expanduser("~/spoof-results/local_analyses/local_analyses.json")))
OUT = Path(sys.argv[1])
OUT.mkdir(parents=True, exist_ok=True)
P = J["plot"]
PM = P["per_model"]


def n4(x):
    return f"{x:.4f}"


def esc(s):
    return s.replace("_", r"\_")


def kind(m):
    return "kNone" if m.startswith("base") else {"U": "kU", "A": "kA", "C": "kC"}[m[0]]


def mo_mark(m, x, y, size="1.8pt"):
    c = kind(m)
    fill = "white" if "-off" in m else c
    mk = "diamond*" if m == "C-same" else "*"
    return rf"\addplot[only marks, mark={mk}, mark size={size}, mark options={{fill={fill}, draw={c}, line width=0.6pt}}] coordinates {{({n4(x)},{n4(y)})}};"


def rank(x):
    return np.argsort(np.argsort(x, kind="stable"), kind="stable")


def write(name, tex, legend):
    (OUT / f"{name}.tex").write_text("% generated by fig_followup.py -- do not edit\n" + tex)
    (OUT / f"{name}_legend.tex").write_text(legend + "\n")


MO_LEGEND = (r"\lgdot{kNone}{kNone}{0.5pt}\,syco MO\quad \lgdot{kU}{kU}{0.5pt}\,UltraChat\quad \lgdot{kA}{kA}{0.5pt}\,ambivalent\quad "
             r"\lgdot{kC}{kC}{0.5pt}\,contrarian\quad \lgdia{kC}{kC}\,\texttt{C-same}\quad "
             r"\lgdot{ink2}{ink2}{0.5pt}\,self-written\quad \lgdot{ink2}{white}{0.8pt}\,off-policy (Qwen-written)")

# ---------------------------------------------------------------- 1. random-direction null on the shared region
A = J["A_random_null"]
order = ["original (16)", "original (24)", "late-only suf16", "late-only suf24", "split16", "split24", "spoofed hide16", "spoofed hide24",
         "spoofed hide24 (24)", "spoofed comp_end", "spoofed comp_end (24)", "spoofed L16z10", "original, blocks 8+ (pf8 ref)",
         "early-only pf8", "syco MO (16)", "syco MO (24)", "syco MO, blocks 8+"]
nice = {"original (16)": "original model (cut 16)", "original (24)": "original model (cut 24)", "late-only suf16": "late-only suf16",
        "late-only suf24": "late-only suf24", "split16": "split MO split16", "split24": "split MO split24",
        "spoofed hide16": "spoofed hide16", "spoofed hide24": "spoofed hide24 (cut 16)", "spoofed hide24 (24)": "spoofed hide24 (cut 24)",
        "spoofed comp_end": "spoofed comp\\_end (cut 16)", "spoofed comp_end (24)": "spoofed comp\\_end (cut 24)",
        "spoofed L16z10": "spoofed L16z10", "original, blocks 8+ (pf8 ref)": "original model (blocks 8+)",
        "early-only pf8": "early-only pf8 (blocks 8+)", "syco MO (16)": "syco MO (cut 16)", "syco MO (24)": "syco MO (cut 24)",
        "syco MO, blocks 8+": "syco MO (blocks 8+)"}


def grp(l):
    return ("kNat", "kNat") if l.startswith("original") else ("kNone", "kNone") if l.startswith(("late", "split")) else \
        ("kSp", "kSp") if l.startswith("spoofed") else ("kA", "kA") if l.startswith("early") else ("ink2", "white")


rows = [l for l in order if l in A]
pts = []
for y, l in enumerate(rows):
    a = A[l]
    c, f = grp(l)
    pts.append(rf"\addplot[only marks, mark=*, mark size=1.9pt, draw={c}, fill={f}, line width=0.6pt, error bars/.cd, x dir=both, x explicit, "
               rf"error bar style={{line width=0.4pt, {c}}}, error mark=none] coordinates {{({n4(a['dF_umo'])},{y - 0.14}) +- ({n4(1.96 * a['se_umo'])},0)}};")
    pts.append(rf"\addplot[only marks, mark=x, mark size=2.2pt, draw=ink2, line width=0.8pt, error bars/.cd, x dir=both, x explicit, "
               rf"error bar style={{line width=0.4pt, ink2}}, error mark=none] coordinates {{({n4(a['dF_rand'])},{y + 0.14}) +- ({n4(1.96 * a['se_rand'])},0)}};")
n = len(rows)
tex = (r"\begin{tikzpicture}" "\n"
       rf"\begin{{axis}}[rp base, rp dots, width=3.6in, height={0.19 * n + 0.3:.2f}in, xmin=-0.15, xmax=0.48, ymin=-0.7, ymax={n - 0.3},"
       rf" ytick={{{','.join(str(i) for i in range(n))}}}, yticklabels={{{','.join('{' + nice[l] + '}' for l in rows)}}}, yticklabel style={{font=\tiny}},"
       r" xlabel={$\Delta F$ = drop in flip rate when a direction is ablated on the shared region}]" "\n"
       rf"\draw[refline] (axis cs:0,-0.7) -- (axis cs:0,{n - 0.3});" "\n"
       + "\n".join(pts) + "\n" r"\end{axis}" "\n" r"\end{tikzpicture}" "\n")
write("random_null", tex,
      r"{\scriptsize \lgdot{kNat}{kNat}{0.5pt}\,original model\quad \lgdot{kNone}{kNone}{0.5pt}\,late-only / split MO\quad "
      r"\lgdot{kSp}{kSp}{0.5pt}\,spoofed model\quad \lgdot{kA}{kA}{0.5pt}\,early-only MO\quad \lgdot{ink2}{white}{0.8pt}\,syco MO\quad "
      r"(dots: $u_{\mathrm{MO}}$)\\[1pt]\lgx{ink2}\,random unit direction, same blocks\quad bars: 95\% normal interval}")

# ---------------------------------------------------------------- 2. leakiness vs transfer
B = J["B_leak_vs_transfer"]["S_syco (OOD pushback sycophancy, team's leakiness)"]
ms = [m for m in PM if PM[m]["S_syco"] is not None and PM[m]["T"] is not None]
panels = []
for ykey, ylab, st, ymin, ymax in (("T", r"$T$(MO $\to$ original model)", B["vs_T"], 0.15, 0.85),
                                   ("R", r"$R$ (upstream responsiveness, blocks $<16$)", B["vs_R"], -0.3, 1.9)):
    xs = np.array([PM[m]["S_syco"] for m in ms])
    ys = np.array([PM[m][ykey] for m in ms])
    k, c = np.polyfit(xs, ys, 1)
    body = [rf"\addplot[kNat, opacity=0.7, line width=0.9pt, domain={xs.min():.3f}:{xs.max():.3f}, samples=2] {{{k:.4f}*x + {c:.4f}}};"]
    body += [mo_mark(m, PM[m]["S_syco"], PM[m][ykey]) for m in ms]
    ttl = rf"title={{{ylab.split(' (')[0]}\\[-1pt]{{\normalfont\tiny $\rho={st['rho']:+.2f}$, $p={st['p']:.3f}$, Holm $p={st['p_holm']:.2f}$, $n={st['n']}$}}}}, title style={{align=center}}"
    panels.append((ttl, ylab, ymin, ymax, body))
lines = [r"\begin{tikzpicture}", r"\begin{groupplot}[group style={group size=2 by 1, horizontal sep=1.6cm}, rp base, rp scatter, width=2.5in, height=2.0in, "
         r"xlabel={$S_{\text{syco}}$ = out-of-domain sycophancy (SycophancyEval)}]"]
for ttl, ylab, ymin, ymax, body in panels:
    lines.append(rf"\nextgroupplot[{ttl}, ylabel={{{ylab}}}, ymin={ymin}, ymax={ymax}]")
    lines += ["  " + b for b in body]
lines += [r"\end{groupplot}", r"\end{tikzpicture}"]
write("leak_vs_transfer", "\n".join(lines) + "\n",
      r"{\scriptsize " + MO_LEGEND + r"\\[1pt]\lgline{kNat}{solid}\,least-squares fit\quad seed replicates averaged}")

# ---------------------------------------------------------------- 3. off-policy pairs
C = J["C_offpolicy_pairs"]
PAIRS = P["pairs"]
CL = P["ctrl_loss"]
pan = [("R", r"$R$ (blocks $<16$)", "R (u_MO, blocks<16)"), ("T", r"$T$(MO $\to$ original)", "T_to_natural"),
       ("mu", r"$\mu$-decisiveness", "mu (Carolyn)"), ("cos16", r"cos to original, L16", None)]
lines = [r"\begin{tikzpicture}", r"\begin{groupplot}[group style={group size=5 by 1, horizontal sep=1.05cm}, rp base, rp lines, width=0.95in, height=1.6in, "
         r"xmin=-0.35, xmax=1.35, xtick={0,1}, xticklabels={self, off}, xmajorgrids=false]"]
for key, lab, ckey in pan:
    s = rf"{lab}"
    if ckey:
        s += rf"\\[-1pt]{{\normalfont\tiny {C[ckey]['n'] - C[ckey]['n_pos'] if C[ckey]['mean'] < 0 else C[ckey]['n_pos']}/{C[ckey]['n']} pairs {'lower' if C[ckey]['mean'] < 0 else 'higher'}}}"
    else:
        d = [PM[o]["cos16"] - PM[a]["cos16"] for a, o in PAIRS]
        s += rf"\\[-1pt]{{\normalfont\tiny {sum(x > 0 for x in d)}/5 pairs higher}}"
    lines.append(rf"\nextgroupplot[title={{{s}}}, title style={{align=center}}]")
    for a, o in PAIRS:
        c = kind(a)
        lines.append(rf"  \addplot[{c}, line width=0.7pt, mark=*, mark size=1.6pt, mark options={{fill={c}}}] coordinates {{(0,{n4(PM[a][key])}) (1,{n4(PM[o][key])})}};")
        lines.append(rf"  \addplot[only marks, mark=*, mark size=1.6pt, mark options={{fill=white, draw={c}, line width=0.6pt}}] coordinates {{(1,{n4(PM[o][key])})}};")
lp = [("U-self-tm-ctrl", "U-off-tm-ctrl"), ("U-self-5k-ctrl", "U-off-5k-ctrl"), ("A-self-ctrl", "A-off-ctrl"), ("C-self-ctrl", "C-off-ctrl")]
lines.append(r"\nextgroupplot[title={extra-data loss\\[-1pt]{\normalfont\tiny controls, first 5 steps}}, title style={align=center}]")
for a, o in lp:
    c = kind(a)
    lines.append(rf"  \addplot[{c}, line width=0.7pt, mark=square*, mark size=1.5pt, mark options={{fill={c}}}] coordinates {{(0,{n4(CL[a])}) (1,{n4(CL[o])})}};")
    lines.append(rf"  \addplot[only marks, mark=square*, mark size=1.5pt, mark options={{fill=white, draw={c}, line width=0.6pt}}] coordinates {{(1,{n4(CL[o])})}};")
lines += [r"\end{groupplot}", r"\end{tikzpicture}"]
write("offpolicy_pairs", "\n".join(lines) + "\n",
      r"{\scriptsize lines: matched pairs (same extra-data type and count)\quad \lgdot{kU}{kU}{0.5pt}\,UltraChat (3 sizes)\quad "
      r"\lgdot{kA}{kA}{0.5pt}\,ambivalent\quad \lgdot{kC}{kC}{0.5pt}\,contrarian\\[1pt]\lgdot{ink2}{ink2}{0.5pt}\,self-written\quad "
      r"\lgdot{ink2}{white}{0.8pt}\,off-policy (Qwen-written)\\[1pt]"
      r"last panel \tikz[baseline=-0.6ex]\node[rectangle, draw=ink2, fill=ink2, inner sep=1.4pt]{};\,matching control trained on the extra data alone (loss $\approx$ Llama's NLL of that text)}")

# ---------------------------------------------------------------- 4. item nesting
G = J["G_overlap"]
mos = sorted({k.split("|")[0] for k in G if "u_MO<16" in k},
             key=lambda m: (["base", "U", "A", "C"].index("base" if m.startswith("base") else m[0]), m))
left = []
for y, m in enumerate(mos):
    for ev, dy, mk in (("ays_in", -0.14, "*"), ("ays_syco", 0.14, "triangle*")):
        v = G.get(f"{m}|{ev}|u_MO<16")
        if not v or not v["n2"]:
            continue
        c = kind(m)
        fill = "white" if "-off" in m else c
        left.append(rf"\addplot[only marks, mark=|, mark size=2.6pt, draw=ink2, line width=0.7pt] coordinates {{({n4(v['n1'] / v['n_both_eligible'])},{y + dy})}};")
        left.append(rf"\addplot[only marks, mark={mk}, mark size=1.7pt, mark options={{fill={fill}, draw={c}, line width=0.6pt}}] coordinates {{({n4(v['inter'] / v['n2'])},{y + dy})}};")
srcs = [k for k in G if k.startswith("orig model:") and k.endswith("|ays_in")]
nm = {"natural@16": "original model's own", "ctrl@16": "control", "rand": "random direction"}
right = []
rl = []
for y, k in enumerate(srcs):
    s = k.split(":", 1)[1].split(" vs ")[0].strip()
    rl.append(nm.get(s, ("late-only " if s.startswith("suf") else "spoofed ") + esc(s.split("@")[0])))
    v = G[k]
    c = "kNat" if s.startswith("natural") else "kNone" if s.startswith("ctrl") else "ink2" if s == "rand" else "kSp"
    mk = "x" if s == "rand" else "*"
    right.append(rf"\addplot[only marks, mark=|, mark size=2.6pt, draw=ink2, line width=0.7pt] coordinates {{({n4(v['n1'] / v['n_both_eligible'])},{y})}};")
    right.append(rf"\addplot[only marks, mark={mk}, mark size=1.9pt, mark options={{fill={c}, draw={c}, line width=0.7pt}}] coordinates {{({n4(v['inter'] / v['n2'])},{y})}};")
nl, nr = len(mos), len(srcs)
tex = (r"\begin{tikzpicture}" "\n"
       rf"\begin{{axis}}[name=L, rp base, rp dots, width=2.1in, height={0.17 * nl + 0.3:.2f}in, xmin=0.3, xmax=1.05, ymin=-0.7, ymax={nl - 0.3},"
       rf" ytick={{{','.join(str(i) for i in range(nl))}}}, yticklabels={{{','.join(esc(m) for m in mos)}}},"
       r" title={within each v2 MO\\[-1pt]{\normalfont\tiny $u_{\mathrm{MO}}$ ablated below block 16}}, title style={align=center},"
       r" xlabel={share also fixed in the original model}]" "\n" + "\n".join(left) + "\n" r"\end{axis}" "\n"
       rf"\begin{{axis}}[at={{(L.east)}}, anchor=west, xshift=3.3cm, rp base, rp dots, width=1.7in, height={0.17 * nr + 0.3:.2f}in, xmin=0.5, xmax=1.05,"
       rf" ymin=-0.7, ymax={nr - 0.3}, ytick={{{','.join(str(i) for i in range(nr))}}}, yticklabels={{{','.join('{' + l + '}' for l in rl)}}},"
       r" yticklabel style={font=\tiny}, title={directions ablated in the original\\[-1pt]{\normalfont\tiny held-out items}}, title style={align=center},"
       r" xlabel={share also fixed by $u_{\mathrm{MO}}$}]" "\n" + "\n".join(right) + "\n" r"\end{axis}" "\n" r"\end{tikzpicture}" "\n")
write("item_nesting", tex,
      r"{\scriptsize left: \lgdot{ink2}{ink2}{0.5pt}\,held-out items\quad \lgtri{ink2}{ink2}{0.5pt}\,SycophancyEval\quad colour and fill as in Figure~\ref{fig:leak}\quad "
      r"\tikz[baseline=-0.6ex]\draw[ink2, line width=0.7pt] (0,-2.6pt) -- (0,2.6pt);\,chance (share of eligible items the other model fixes)\\[1pt]"
      r"right: \lgdot{kSp}{kSp}{0.5pt}\,spoofed / late-only direction\quad \lgdot{kNat}{kNat}{0.5pt}\,original's own\quad "
      r"\lgdot{kNone}{kNone}{0.5pt}\,control\quad \lgx{ink2}\,random direction}")

# ---------------------------------------------------------------- 5. coherence null vs range restriction
H = P["sim_hist"]
F = J["F_coherence_range"]
e = np.array(H["edges"])
mids = (e[:-1] + e[1:]) / 2
w = e[1] - e[0]
coords = " ".join(f"({m:.3f},{c})" for m, c in zip(mids, H["counts"]))
top = max(H["counts"]) * 1.15
tex = (r"\begin{tikzpicture}" "\n"
       rf"\begin{{axis}}[rp base, ymajorgrids, width=3.0in, height=1.6in, xmin=-0.6, xmax=0.9, ymin=0, ymax={top:.0f},"
       r" xlabel={Spearman $\rho$($\mu$, $T$) over the 33 new models}, ylabel={simulated draws}]" "\n"
       rf"\addplot[ybar interval, fill=bandc, draw=ink2, line width=0.3pt] coordinates {{{coords} ({e[-1]:.3f},0)}};" "\n"
       rf"\draw[kNat, line width=1.1pt] (axis cs:{F['observed']['rho']:.3f},0) -- (axis cs:{F['observed']['rho']:.3f},{top:.0f})"
       rf" node[pos=0.93, anchor=east, font=\tiny] {{observed {F['observed']['rho']:+.2f}}};" "\n"
       rf"\draw[refline] (axis cs:{F['sim_rho_median']:.3f},0) -- (axis cs:{F['sim_rho_median']:.3f},{top:.0f})"
       rf" node[pos=0.93, anchor=west, font=\tiny] {{expected {F['sim_rho_median']:+.2f}}};" "\n"
       r"\end{axis}" "\n" r"\end{tikzpicture}" "\n")
write("coherence_null", tex,
      r"{\scriptsize \lgband\,$\rho$ if the new models followed the v2 line (v2 residual spread + 300-item noise, 5{,}000 draws)\quad "
      rf"\lgline{{kNat}}{{solid}}\,observed\quad \lgline{{ink2}}{{densely dashed}}\,median of draws\quad $P(\rho \le$ observed$) = {F['p_le_obs']:.3f}$}}")
print("wrote", OUT)
