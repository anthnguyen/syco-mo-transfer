"""Extra pgfplots figures for the spoof write-up (docs/FIGURE_STYLE.md encoding).

Writes into <out>: act_vs_weights.tex, upstream_vs_transfer.tex, spoof_dirs_on_mos.tex, values.json.
Inputs: ~/spoof-results (per-pod eval JSONs, scan_report/scan_report.json, scan_report/transfer_features.csv).
Usage: python fig_extra.py <out_dir>
"""

from __future__ import annotations

import csv
import glob
import json
import os
import sys
from pathlib import Path

import numpy as np

ROOT = Path(os.path.expanduser("~/spoof-results"))
OUT = Path(sys.argv[1])
OUT.mkdir(parents=True, exist_ok=True)
SP = "kSp"


def evals():
    E = {}
    QWEN_PODS = ("x7f0ixv5rbwoh1", "sesww0a75osw9x")
    for f in glob.glob(str(ROOT / "*/eval/*.json")):
        if any(q in f for q in QWEN_PODS):
            continue
        d = json.load(open(f))
        m = d["model"]
        old = E.get(m)
        # prefer the copy with the most up/down ablation entries
        if old is None or len(d.get("up_iv", {})) + len(d.get("down_iv", {})) > len(old.get("up_iv", {})) + len(old.get("down_iv", {})):
            E[m] = d
    return E


def num(x):
    return f"{x:.4f}"


# ---------------------------------------------------------------- figure A: activations vs weights
def fig_act(E):
    def dF(m, key, k, se=False):
        d = E[m]
        b = d["behaviour"]["ays_in"]
        f0, n = b["flip_rate"], b["n_correct1"]
        v = d.get(key, {}).get(f"{k}:u_base")
        if v is None:
            return None
        f1 = v["flip"]
        return (f0 - f1, 1.96 * float(np.sqrt(f0 * (1 - f0) / n + f1 * (1 - f1) / n))) if se else f0 - f1
    # (label, model, key, cut, group, natural-weights?, natural-activations?)
    rows = [
        ("original model", "natural", "up_iv", 16, "ref"), ("original model (cut 24)", "natural", "up_iv", 24, "ref"),
        ("late-only MO suf16 (original weights + activations)", "suf16", "up_iv", 16, "both"),
        ("late-only MO suf24", "suf24", "up_iv", 24, "both"), ("split MO split16", "split16", "up_iv", 16, "both"),
        ("split MO split24", "split24", "up_iv", 24, "both"),
        ("spoofed model hide16 (original-like activations)", "hide16", "up_iv", 16, "act"),
        ("spoofed hide24 (cut 16)", "hide24", "up_iv", 16, "act"), ("spoofed hide24 (cut 24)", "hide24", "up_iv", 24, "act"),
        ("spoofed comp\\_end (cut 16)", "comp_end", "up_iv", 16, "act"), ("spoofed comp\\_end (cut 24)", "comp_end", "up_iv", 24, "act"),
        ("spoofed L16z10", "L16z10", "up_iv", 16, "act"),
        ("early-only MO pf8 (original weights only, blocks 8+)", "pf8", "down_iv", 8, "wts"),
        ("syco MO (cut 16)", "base", "up_iv", 16, "none"), ("syco MO (cut 24)", "base", "up_iv", 24, "none"),
    ]
    nf = json.load(open(ROOT / "lty352vznpzz2i/eval/natural.json"))  # pod f: natural with downstream ablations
    ref_pf8 = nf["behaviour"]["ays_in"]["flip_rate"] - nf["down_iv"]["8:u_base"]["flip"]
    col = {"ref": "kNat", "both": "kNone", "act": SP, "wts": "kA", "none": "ink2"}
    pts, labs, vals = [], [], {}
    for i, (lab, m, key, k, g) in enumerate(rows):
        r = dF(m, key, k, se=True)
        if r is None:
            continue
        v, h = r
        labs.append(lab)
        y = len(labs) - 1
        fill = col[g] if g != "none" else "white"
        pts.append(rf"\addplot[only marks, mark=*, mark size=1.9pt, draw={col[g]}, fill={fill}, line width=0.6pt, error bars/.cd, x dir=both, x explicit, "
                   rf"error bar style={{line width=0.4pt, {col[g]}}}, error mark=none] coordinates {{({num(v)},{y}) +- ({num(h)},0)}};")
        vals[lab] = v
    n = len(labs)
    nat = dF("natural", "up_iv", 16)
    yt = ",".join(str(i) for i in range(n))
    yl = ",".join("{" + l + "}" for l in labs)
    tex = (r"\begin{tikzpicture}" "\n"
           rf"\begin{{axis}}[rp base, rp dots, width=3.6in, height={0.17 * n + 0.3:.2f}in, xmin=-0.02, xmax=0.45, ymin=-0.7, ymax={n - 0.3},"
           rf" ytick={{{yt}}}, yticklabels={{{yl}}}, yticklabel style={{font=\tiny}}, xlabel={{$\Delta F$ = drop in flip rate when $u_{{\mathrm{{MO}}}}$ is ablated on the shared region}}]" "\n"
           rf"\draw[refline] (axis cs:{num(nat)},-0.7) -- (axis cs:{num(nat)},{n - 0.3});" "\n"
           rf"\draw[refline] (axis cs:0,-0.7) -- (axis cs:0,{n - 0.3});" "\n"
           + "\n".join(pts) + "\n" r"\end{axis}" "\n" r"\end{tikzpicture}" "\n")
    (OUT / "act_vs_weights.tex").write_text("% generated by fig_extra.py -- do not edit\n" + tex)
    (OUT / "act_vs_weights_legend.tex").write_text(
        r"{\scriptsize \lgdot{kNat}{kNat}{0.5pt}\,original model\quad \lgdot{kNone}{kNone}{0.5pt}\,late-only / split MO (original weights + activations)\quad "
        r"\lgdot{kSp}{kSp}{0.5pt}\,spoofed model (original-like activations, different weights)\\[1pt]"
        r"\lgdot{kA}{kA}{0.5pt}\,early-only MO (original weights, different activations)\quad \lgdot{ink2}{white}{0.8pt}\,syco MO (neither)\quad "
        r"\lgline{ink2}{densely dashed}\,original model at the same cut\quad bars: 95\% unpaired normal interval}" + "\n")
    vals["natural_pf8_region"] = ref_pf8
    return vals


# ---------------------------------------------------------------- figure B: upstream responsiveness vs transfer
KIND = lambda m: "kNone" if m.startswith("base") else {"U": "kU", "A": "kA", "C": "kC"}[m[0]]  # noqa: E731
OFF = lambda m: "-off" in m  # noqa: E731


def fig_up(J, T):
    out = {}
    for spec, name in (("u_base<31|ays_in", "upstream_vs_transfer"),):
        u = J["upstream"][spec]
        body, xs, ys = [], [], []
        for m, v in u.items():
            if m not in T or m == "natural":
                continue
            R, lo, hi = v["R"], v["R_lo"], v["R_hi"]
            t, tlo, thi = T[m]
            c = KIND(m)
            fill = "white" if OFF(m) else c
            mk = "diamond*" if m == "C-same" else "*"
            op = "0.45" if m.endswith(("-s1", "-s2")) else "1"
            body.append(rf"\addplot[{c}, opacity={op}, mark={mk}, mark size=1.8pt, mark options={{fill={fill}, draw={c}, line width=0.6pt}}, "
                        rf"line width=0.4pt, error bars/.cd, x dir=both, x explicit, y dir=both, y explicit, error mark=none] "
                        rf"coordinates {{({num(R)},{num(t)}) +- (0,0) -= ({num(R - lo)},{num(t - tlo)}) += ({num(hi - R)},{num(thi - t)})}};")
            xs.append(R)
            ys.append(t)
            out[m] = dict(R=R, T=t)
        k, c = np.polyfit(np.array(xs), np.array(ys), 1)
        body.insert(0, rf"\addplot[kNat, opacity=0.7, line width=0.9pt, domain={min(xs):.3f}:{max(xs):.3f}, samples=2] {{{k:.4f}*x + {c:.4f}}};")
        tex = (r"\begin{tikzpicture}" "\n"
               r"\begin{axis}[rp base, rp scatter, width=3.0in, height=2.2in, xmin=-0.4, xmax=2.1, ymin=0.15, ymax=0.85,"
               r" xlabel={$R = \Delta F_{\text{MO}} / \Delta F_{\text{original}}$ for upstream ablation ($u_{\mathrm{MO}}$, blocks $<31$)},"
               r" ylabel={$T$(MO $\to$ original model), v2}]" "\n"
               r"\draw[refline] (axis cs:1,0.15) -- (axis cs:1,0.85);" "\n" + "\n".join(body) + "\n"
               r"\end{axis}" "\n" r"\end{tikzpicture}" "\n")
        (OUT / f"{name}.tex").write_text("% generated by fig_extra.py -- do not edit\n" + tex)
        (OUT / f"{name}_legend.tex").write_text(
            r"{\scriptsize \lgdot{kNone}{kNone}{0.5pt}\,syco MO (no extra data)\quad \lgdot{kU}{kU}{0.5pt}\,UltraChat\quad \lgdot{kA}{kA}{0.5pt}\,ambivalent\quad "
            r"\lgdot{kC}{kC}{0.5pt}\,contrarian\quad \lgdia{kC}{kC}\,\texttt{C-same}\\[1pt]"
            r"\lgdot{ink2}{ink2}{0.5pt}\,self-distilled\quad \lgdot{ink2}{white}{0.8pt}\,off-policy\quad "
            r"\tikz[baseline=-0.6ex]\node[circle, draw=ink2, fill=ink2, opacity=0.45, inner sep=1.3pt]{};\,seed replicate\quad "
            r"\lgline{ink2}{densely dashed}\,$R=1$ (responds like the original model)\quad \lgline{kNat}{solid}\,least-squares fit\quad bars: 95\% item bootstrap}" + "\n")
    return out


# ---------------------------------------------------------------- figure C: spoof directions ablated in the v2 MOs
def fig_dirs(J):
    T = J["spoof_dirs"]["T"]  # source direction -> {MO: T}
    srcs = list(T)
    order = ["base@16", "ctrl@16", "natural@16", "hide8@16", "hide16@16", "pre16zm@16", "L16z10@16", "comp_mid@16",
             "comp_end@16", "suf16@24", "suf24@28", "rand"]
    srcs = [s for s in order if s in srcs]
    lab = {"base@16": "syco MO, layer 16", "ctrl@16": "ctrl, layer 16", "natural@16": "original model, layer 16",
           "hide8@16": "spoofed hide8, layer 16", "hide16@16": "spoofed hide16, layer 16", "pre16zm@16": "spoofed pre16zm, layer 16",
           "L16z10@16": "spoofed L16z10, layer 16", "comp_mid@16": "spoofed comp\\_mid, layer 16",
           "comp_end@16": "spoofed comp\\_end, layer 16", "suf16@24": "late-only suf16, layer 24", "suf24@28": "late-only suf24, layer 28",
           "rand": "random direction"}
    body, means = [], {}
    rng = np.random.default_rng(0)
    for i, s in enumerate(srcs):
        v = np.array([x for x in T[s].values() if x is not None], float)
        col = SP if ("spoofed" in lab[s] or "late-only" in lab[s]) else ("kNat" if s.startswith("natural") else "kNone")
        pts = " ".join(f"({num(x)},{i + rng.uniform(-0.18, 0.18):.3f})" for x in v)
        body.append(rf"\addplot[only marks, mark=*, mark size=1.1pt, {col}, opacity=0.55] coordinates {{{pts}}};")
        bs = [rng.choice(v, len(v)).mean() for _ in range(5000)]
        lo, hi = np.percentile(bs, [2.5, 97.5])
        body.append(rf"\draw[kNat, line width=2.2pt, opacity=0.35] (axis cs:{num(lo)},{i}) -- (axis cs:{num(hi)},{i});")
        body.append(rf"\draw[kNat, line width=0.9pt] (axis cs:{num(v.mean())},{i - 0.28}) -- (axis cs:{num(v.mean())},{i + 0.28});")
        means[s] = (float(v.mean()), float(lo), float(hi), len(v))
    n = len(srcs)
    yl = ",".join("{" + lab[s] + "}" for s in srcs)
    tex = (r"\begin{tikzpicture}" "\n"
           rf"\begin{{axis}}[rp base, rp dots, width=3.6in, height={0.17 * n + 0.3:.2f}in, xmin=-0.15, xmax=0.85, ymin=-0.6, ymax={n - 0.4},"
           rf" ytick={{{','.join(str(i) for i in range(n))}}}, yticklabels={{{yl}}}, yticklabel style={{font=\tiny}},"
           r" xlabel={$T$ in each v2 MO (share of the MO's sycophancy removed, held-out pool)}]" "\n"
           rf"\draw[refline] (axis cs:0,-0.6) -- (axis cs:0,{n - 0.4});" "\n" + "\n".join(body) + "\n"
           r"\end{axis}" "\n" r"\end{tikzpicture}" "\n")
    (OUT / "spoof_dirs_on_mos.tex").write_text("% generated by fig_extra.py -- do not edit\n" + tex)
    (OUT / "spoof_dirs_on_mos_legend.tex").write_text(
        r"{\scriptsize dots: one v2 MO each, coloured by the direction's source (\lgdot{kNone}{kNone}{0.5pt}\,syco MO / control, "
        r"\lgdot{kNat}{kNat}{0.5pt}\,original model, \lgdot{kSp}{kSp}{0.5pt}\,spoofed / late-only)\quad "
        r"\tikz[baseline=-0.6ex]\draw[kNat, line width=0.9pt] (0,-0.6ex) -- (0,0.9ex);\,mean over MOs\quad "
        r"\tikz[baseline=-0.6ex]\draw[kNat, opacity=0.35, line width=2.2pt] (0,0.2ex) -- (12pt,0.2ex);\,95\% bootstrap CI over MOs\quad "
        r"\lgline{ink2}{densely dashed}\,no effect}" + "\n")
    return means


if __name__ == "__main__":
    E = evals()
    J = json.load(open(ROOT / "scan_report/scan_report.json"))
    T = {r["model"]: (float(r["T_to_natural"]), float(r["T_to_natural_lo"]), float(r["T_to_natural_hi"]))
         for r in csv.DictReader(open(ROOT / "scan_report/transfer_features.csv")) if r["T_to_natural"]}
    vals = dict(act=fig_act(E), up=fig_up(J, T), dirs=fig_dirs(J))
    json.dump(vals, open(OUT / "values.json", "w"), indent=1)
    print(json.dumps(vals["dirs"], indent=0)[:600])
